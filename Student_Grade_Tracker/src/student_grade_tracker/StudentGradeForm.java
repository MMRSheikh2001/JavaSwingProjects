    private void btnDeleteMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btnDeleteMouseClicked
        // TODO add your handling code here:

        int row = tblGradeTracker.getSelectedRow();
        String id = tblGradeTracker.getModel().getValueAt(row, 0).toString();
        int idStu = -1;
        try {
            idStu = Integer.parseInt(id) - 1;
        } catch (Exception e) {
            return;
        }

        if (idStu >= 0) {
            list.remove(idStu);
        } else {
            JOptionPane.showMessageDialog(null, "First Select a table item to delete");
            return;

        }
        clearData();
        showGradeTable();


    }//GEN-LAST:event_btnDeleteMouseClicked

    public void clearData() {
        txtName.setText("");
        txtScore.setText("");
    }

    public void showGradeTable() {

        String[] stuList = {"SL", "Name", "Score", "Grade"};

        DefaultTableModel model = new DefaultTableModel();

        model.setColumnIdentifiers(stuList);

        tblGradeTracker.setModel(model);

        for (int i = 0; i < list.size(); i++) {
            Student s = list.get(i);
            model.addRow(new Object[]{(i + 1), s.getName(), s.getScore(), s.getLetterGrade()});

        }

        if (!list.isEmpty()) {

            showAverageScore.setText(getAverage() + "");
            showHighestName.setText(getHighest().getName());
            showHighestScore.setText(getHighest().getScore() + "");

            showLowestName.setText(getLowest().getName());
            showLowestScore.setText(getLowest().getScore() + "");

        } else {

            showAverageScore.setText(0 + "");
            showHighestName.setText("");
            showHighestScore.setText("");

            showLowestName.setText("");
            showLowestScore.setText("");

        }

    }

    // Calulations
    private double getAverage() {
        double sum = 0;
        for (Student s : list) {
            sum += s.getScore();
        }
        return sum / list.size();
    }

    private Student getHighest() {
        Student best = list.get(0);
        for (Student s : list) {
            if (s.getScore() > best.getScore()) {
                best = s;
            }
        }
        return best;
    }

    private Student getLowest() {
        Student worst = list.get(0);
        for (Student s : list) {
            if (s.getScore() < worst.getScore()) {
                worst = s;

            }
        }
        return worst;
    }

