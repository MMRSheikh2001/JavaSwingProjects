    private void tblShowUsersMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblShowUsersMouseClicked
        // TODO add your handling code here:

        int row = tblShowUsers.getSelectedRow();
        if (row >= 0) {

            String id = tblShowUsers.getModel().getValueAt(row, 0).toString();
            String userName = tblShowUsers.getModel().getValueAt(row, 1).toString();
            String password = tblShowUsers.getModel().getValueAt(row, 2).toString();
            String cashBalance = tblShowUsers.getModel().getValueAt(row, 3).toString();

            txtUserId.setText(id);
            txtUserName.setText(userName);

            txtPassword.setText(password);
            txtCashBalance.setText(cashBalance);

        }


    }//GEN-LAST:event_tblShowUsersMouseClicked

    private void btnUpdateUserMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btnUpdateUserMouseClicked
        // TODO add your handling code here:

        String id = txtUserId.getText().trim();
        String userName = txtUserName.getText().trim().toLowerCase();
        String password = txtPassword.getText().trim();
        String cashBalance = txtCashBalance.getText().trim();

        if (id.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Select a user from the table first");
            return;
        }

        if (userName.isEmpty() || password.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Give valid User Name and Password");
            return;

        }

        Double balance;
        try {
            balance = Double.valueOf(cashBalance);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(null, "Give Proper Balance" + e);
            return;
        }

        if (balance < 0) {
            JOptionPane.showMessageDialog(null, "Balance cannot be negative");
            return;
        }

        User user = userDao.findById(Long.valueOf(id));

        if (user == null) {
            JOptionPane.showMessageDialog(null, "User not found");
            return;
        }

        User sameName = userDao.findByUserName(userName);

        if (sameName != null && !sameName.getId().equals(user.getId())) {
            JOptionPane.showMessageDialog(null, "User Name Already exists");
            return;
        }

        user.setUserName(userName);
        user.setPassword(password);
        user.setCashBalance(balance);

        userDao.update(user);

        showUsers();
        clearData();
    }//GEN-LAST:event_btnUpdateUserMouseClicked

    public void showUsers() {
        String[] list = {"SL", "User Name", "Password", "Available Balance"};
        DefaultTableModel model = new DefaultTableModel();
        model.setColumnIdentifiers(list);
        tblShowUsers.setModel(model);
        List<User> uList = userDao.findAll();
        for (User u : uList) {
            model.addRow(new Object[]{u.getId(), u.getUserName(), u.getPassword(), u.getCashBalance()});
        }

    }

    private void clearData() {
        txtUserName.setText("");
        txtCashBalance.setText("0");
        txtPassword.setText("");
        txtUserId.setText("");

    }

